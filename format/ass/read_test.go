// Ports testWindows1252FileReadAsUtf8KeepsItsLinesAndSpeaker of tests/Parsers/AssParserTest.php of
// subtitle-toolbox-php. The bytes 0xE9, 0xE8, 0xE0, 0xFB and 0x80 are the Windows-1252 letters of the file.
func TestWindows1252FileReadAsUTF8KeepsItsLinesAndSpeaker(t *testing.T) {
	t.Parallel()

	s, warnings, err := ass.Read(bytes.NewReader(testfiles.Read(t, "ass/own_windows_1252.ass")), model.CommonReadOptions{}, ass.ReadOptions{})
	require.NoError(t, err)
	assert.Empty(t, warnings)
	assert.Equal(t, [][]string{
		{"<v H\xe9l\xe8ne>Le caf\xe9 ouvre \xe0 sept heures."},
		{"<i>Cr\xe8me br\xfbl\xe9e</i>", "\xe0 4 \x80"},
		{"<v H\xe9l\xe8ne>See you tomorrow."},
	}, linesOf(s))
}

func linesOf(s *model.Subtitle) [][]string {
	var out [][]string
	for _, c := range s.All() {
		out = append(out, c.Lines)
	}
	return out
}

