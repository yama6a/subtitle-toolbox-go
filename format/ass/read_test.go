// Ports testOverrideTagsBecomeCoreMarkup of tests/Parsers/AssParserTest.php of subtitle-toolbox-php, then adds
// the rows of the tag table of https://github.com/yama6a/subtitle-toolbox-go/issues/22.
func TestOverrideTagsBecomeCoreMarkup(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		text string
		want []string
	}{
		{"bold and italic", `{\b1}a{\b0} {\i1}b{\i0}`, []string{"<b>a</b> <i>b</i>"}},
		{"open tag closes at the end", `{\u1}a`, []string{"<u>a</u>"}},
		{"empty value resets", `{\s1}a{\s}b`, []string{"<s>a</s>b"}},
		{"weight is no core markup", `{\b700}a`, []string{"a"}},
		{"BGR colour", `{\c&H0000FF&}red`, []string{`<font color="#ff0000">red</font>`}},
		{"primary colour", `{\1c&HFF0000&}blue`, []string{`<font color="#0000ff">blue</font>`}},
		{"short colour", `{\c&HFF&}red`, []string{`<font color="#ff0000">red</font>`}},
		{"colour without the closing &", `{\c&HFF}red`, []string{`<font color="#ff0000">red</font>`}},
		{"8-digit colour drops the alpha byte", `{\c&H80FF0000&}blue`, []string{`<font color="#0000ff">blue</font>`}},
		{"colour reset", `{\c&H00FF00&}a{\c}b`, []string{`<font color="#00ff00">a</font>b`}},
		{"colour without digits is dropped", `{\c&H&}a`, []string{"a"}},
		{"border colour is dropped", `{\3c&H0000FF&}a`, []string{"a"}},
		{"tags nest", `{\b1}a{\i1}b{\b0}c{\i0}d`, []string{"<b>a<i>b</i></b><i>c</i>d"}},
		{"a toggle to the current state writes nothing", `{\b1}a{\b1}b`, []string{"<b>ab</b>"}},
		{"reset closes all", `{\b1\i1}a{\r}b`, []string{"<b><i>a</i></b>b"}},
		{"reset to style", `{\b1}a{\rSign}b`, []string{"<b>a</b>b"}},
		{"reset to an unknown style", `{\b1}a{\rUnknown}b`, []string{"<b>a</b>b"}},
		{"animation is skipped", `{\t(0,500,\b1\1c&H0000FF&)}a`, []string{"a"}},
		{"position and fade are dropped", `{\pos(10,20)\fad(200,200)\fs40\bord2}a`, []string{"a"}},
		{"comment block", "a{note}b", []string{"ab"}},
		{"brace without end is text", "a{b", []string{"a{b"}},
		{"drawing", `{\p1}m 0 0 l 10 0{\p0}text`, []string{"text"}},
		{"drawing scale 4", `{\p4}m 0 0{\p00}text`, []string{"text"}},
		{"escaped text", "1 < 2 & 3 > 2", []string{"1 &lt; 2 &amp; 3 &gt; 2"}},
		{"hard break", `a\Nb`, []string{"a", "b"}},
		{"soft break", `a\nb`, []string{"a b"}},
		{"hard space", `a\hb`, []string{"a\xc2\xa0b"}},
		{"empty tag pair goes", `{\i1}{\i0}a`, []string{"a"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			assert.Equal(t, tt.want, event(t, tt.text).Lines)
		})
	}
}

